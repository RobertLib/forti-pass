/* FortiPass service worker — makes the app usable with no network at all.

   Generated by build/build.js from build/sw.template.js — edit the template.
   ASSET_VERSION is a hash of every cached asset, computed by the build, and
   matches the ?v= query on every script and stylesheet: any change to them
   installs a fresh cache, so a page never mixes new HTML with stale
   JavaScript or CSS from an older one. */

const ASSET_VERSION = "1375b3f035";
// Cache Storage belongs to the whole origin, which on github.io is shared
// with every other repository the account publishes — so only caches with
// this prefix are ours to replace.
const CACHE_PREFIX = "fortipass-";
const CACHE_VERSION = CACHE_PREFIX + "v" + ASSET_VERSION;

// Every page, relative to the scope (the folder this file lives in).
const PAGES = [
  "",
  "cs/",
  "passphrase-generator/",
  "cs/generator-hesel-ze-slov/",
  "pin-generator/",
  "cs/generator-pin/",
  "password-strength-checker/",
  "cs/kontrola-sily-hesla/",
  "wifi-password-generator/",
  "cs/generator-hesla-wifi/",
  "how-long-to-crack-a-password/",
  "cs/jak-dlouho-trva-prolomit-heslo/",
];

const VERSIONED = [
  "styles.css",
  "wordlist-en.js",
  "wordlist-cs.js",
  "locale-cs.js",
  "core.js",
  "qr.js",
  "script.js",
].map((file) => file + "?v=" + ASSET_VERSION);

const STATIC = [
  "manifest.json",
  "cs/manifest.json",
  "favicon.svg",
  "icon.svg",
  "icon-192.png",
  "icon-512.png",
  "icon-maskable-512.png",
  "apple-touch-icon.png",
];

const SHELL = PAGES.map((page) => page || "./").concat(VERSIONED, STATIC);

// How long a page request may hang before the cached copy is shown instead.
const NETWORK_TIMEOUT_MS = 4000;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE_VERSION)
      // Bypass the HTTP cache so a new version never stores stale copies.
      .then((cache) =>
        cache.addAll(SHELL.map((url) => new Request(url, { cache: "reload" })))
      )
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_VERSION)
            .map((key) => caches.delete(key))
        )
      )
      .then(() => self.clients.claim())
  );
});

/**
 * The PAGES entry a navigation is for ("" for the home page, "cs/" for the
 * Czech one…), with or without a trailing index.html — or null for anything
 * else in scope, such as robots.txt or the search-console file.
 */
function pageFor(url) {
  const scope = new URL(self.registration.scope);
  if (url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) {
    return null;
  }
  let rest = url.pathname.slice(scope.pathname.length);
  if (rest === "index.html" || rest.endsWith("/index.html")) {
    rest = rest.slice(0, -"index.html".length);
  }
  return PAGES.indexOf(rest) === -1 ? null : rest;
}

function cacheUrl(page) {
  return new URL(page || "./", self.registration.scope).href;
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    // Anything that is not one of our pages (a 404, a verification file) is
    // left to the browser, so it can never end up cached as the app.
    const page = pageFor(url);
    if (page === null) return;

    // Network first so updates land, and the fresh copy is cached. Offline,
    // the cached page — or that language's home page if this one was never
    // cached. On a connection that hangs, the cached page after a few
    // seconds, while the network copy still lands in the cache for next time.
    // Revalidated rather than taken from the HTTP cache: GitHub Pages lets a
    // page be cached for ten minutes, and a stale copy stored here would
    // overwrite the fresh one the new worker just installed.
    const network = fetch(new Request(request, { cache: "no-cache" })).then((response) => {
      const type = response.headers.get("content-type") || "";
      if (response.ok && type.indexOf("text/html") !== -1) {
        const copy = response.clone();
        event.waitUntil(
          caches.open(CACHE_VERSION).then((cache) => cache.put(cacheUrl(page), copy))
        );
      }
      return response;
    });
    // Keeps the worker alive until the network answers, even if the cached
    // page was served first.
    event.waitUntil(network.catch(() => undefined));

    event.respondWith(
      new Promise((resolve) => {
        let answered = false;
        const answer = (response) => {
          if (answered || !response) return;
          answered = true;
          resolve(response);
        };
        const timer = setTimeout(() => {
          caches.match(cacheUrl(page)).then(answer);
        }, NETWORK_TIMEOUT_MS);
        network.then(
          (response) => {
            clearTimeout(timer);
            answer(response);
          },
          () => {
            clearTimeout(timer);
            const home = cacheUrl(page.startsWith("cs/") ? "cs/" : "");
            caches
              .match(cacheUrl(page))
              // The home page's HTML at this deeper address would resolve
              // its relative links and assets wrongly, so go there instead.
              .then((cached) =>
                cached ||
                caches.match(home).then((fallback) => (fallback ? Response.redirect(home, 302) : null))
              )
              .then((response) => answer(response || Response.error()));
          }
        );
      })
    );
    return;
  }

  // Assets: their URLs are versioned, so a cached copy is always the right
  // one. Anything missing is fetched and kept for next time.
  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response.ok && response.type === "basic") {
          const copy = response.clone();
          event.waitUntil(
            caches.open(CACHE_VERSION).then((cache) => cache.put(request, copy))
          );
        }
        return response;
      });
    })
  );
});
