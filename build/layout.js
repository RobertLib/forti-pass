"use strict";

/* The app shell shared by every page: <head> with SEO metadata and the
   Content Security Policy, the top bar with the three app sections
   (a bottom tab bar on phones), the footer and the dialogs. */

const crypto = require("node:crypto");
const { esc, text, icon, SPRITE_SYMBOLS } = require("./html");
const site = require("./site");

// Applies the saved theme before first paint to avoid a flash of the wrong
// colours. It is the only inline script; the CSP allows it by hash.
const THEME_SCRIPT = `
      (function () {
        try {
          var t = localStorage.getItem("fortipass:theme");
          if (t === "light" || t === "dark") {
            document.documentElement.dataset.theme = t;
          }
        } catch (e) {}
      })();
    `;
const THEME_HASH = crypto.createHash("sha256").update(THEME_SCRIPT, "utf8").digest("base64");

const CSP = [
  "default-src 'self'",
  `script-src 'self' 'sha256-${THEME_HASH}'`,
  "style-src 'self'",
  "img-src 'self'",
  "connect-src 'none'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
].join("; ");

// Browser chrome colours; script.js and the manifests use the same values.
const THEME_COLORS = { light: "#f6f7fb", dark: "#0c0e14" };

// The English copy is British (colour, licence), so it says so.
const OG_LOCALE = { en: "en_GB", cs: "cs_CZ" };
const OG_IMAGE = { en: "og-image.png", cs: "og-image-cs.png" };
const OG_ALT = {
  en: "FortiPass logo with the tagline “Strong passwords, made on your device” and a sample generated password",
  cs: "Logo FortiPass se sloganem „Silná hesla vytvořená ve vašem zařízení“ a ukázkou vygenerovaného hesla",
};

function jsonLd(data) {
  // Any "<" is written as \u003c, still valid JSON: then neither "</script>"
  // nor "<!--" inside a string can end or confuse the script element.
  return `<script type="application/ld+json">
${JSON.stringify(data, null, 2).replace(/</g, "\\u003c")}
    </script>`;
}

function structuredData(ctx, content) {
  const { page, lang, url } = ctx;
  const blocks = [];
  if (page.type === "article") {
    blocks.push({
      "@context": "https://schema.org",
      "@type": "Article",
      headline: text(content.h1),
      description: content.description,
      inLanguage: lang,
      url: url,
      datePublished: "2026-11-09",
      dateModified: site.UPDATED,
      image: site.SITE_URL + OG_IMAGE[lang],
      author: { "@type": "Person", name: site.AUTHOR },
      publisher: { "@type": "Person", name: site.AUTHOR },
    });
  } else {
    blocks.push({
      "@context": "https://schema.org",
      "@type": "WebApplication",
      name: "FortiPass – " + text(ctx.t.toolNames[page.id]),
      description: content.description,
      url: url,
      inLanguage: lang,
      applicationCategory: "SecurityApplication",
      operatingSystem: "Any",
      browserRequirements: "Requires JavaScript",
      isAccessibleForFree: true,
      offers: { "@type": "Offer", price: "0", priceCurrency: lang === "cs" ? "CZK" : "USD" },
      author: { "@type": "Person", name: site.AUTHOR },
    });
  }
  if (content.faq && content.faq.length) {
    blocks.push({
      "@context": "https://schema.org",
      "@type": "FAQPage",
      inLanguage: lang,
      mainEntity: content.faq.map(([question, answer]) => ({
        "@type": "Question",
        name: text(question),
        acceptedAnswer: { "@type": "Answer", text: text(answer) },
      })),
    });
  }
  return blocks.map(jsonLd).join("\n    ");
}

function head(ctx, content) {
  const { lang, root, url, page } = ctx;
  const v = "?v=" + ctx.assetVersion;
  const alternates = site.LANGUAGES.map(
    (code) =>
      `<link rel="alternate" hreflang="${code}" href="${site.SITE_URL}${page.paths[code]}" />`
  ).concat(
    `<link rel="alternate" hreflang="x-default" href="${site.SITE_URL}${page.paths.en}" />`
  );
  const ogImage = site.SITE_URL + OG_IMAGE[lang];
  const manifest = lang === "en" ? "manifest.json" : lang + "/manifest.json";

  return `<head>
    <meta charset="UTF-8" />
    <!-- Generated by build/build.js — edit the sources in build/, not this file.
         Defence in depth: only this site's own files may run or load, and
         connect-src 'none' makes "no network requests" a browser-enforced
         rule. The hash is the inline theme script below. -->
    <meta http-equiv="Content-Security-Policy" content="${CSP}" />
    <meta name="referrer" content="no-referrer" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover" />

    <title>${esc(content.title)}</title>
    <meta name="description" content="${esc(content.description)}" />
    <meta name="author" content="${esc(site.AUTHOR)}" />
    <meta name="robots" content="index, follow" />
    <meta name="color-scheme" content="dark light" />
    <meta name="theme-color" content="${THEME_COLORS.dark}" media="(prefers-color-scheme: dark)" />
    <meta name="theme-color" content="${THEME_COLORS.light}" media="(prefers-color-scheme: light)" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-title" content="FortiPass" />

    <link rel="canonical" href="${url}" />
    ${alternates.join("\n    ")}

    <meta property="og:type" content="${page.type === "article" ? "article" : "website"}" />
    <meta property="og:url" content="${url}" />
    <meta property="og:site_name" content="FortiPass" />
    <meta property="og:locale" content="${OG_LOCALE[lang]}" />
    ${site.LANGUAGES.filter((code) => code !== lang)
      .map((code) => `<meta property="og:locale:alternate" content="${OG_LOCALE[code]}" />`)
      .join("\n    ")}
    <meta property="og:title" content="${esc(content.ogTitle || content.title)}" />
    <meta property="og:description" content="${esc(content.description)}" />
    <meta property="og:image" content="${ogImage}" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta property="og:image:alt" content="${esc(OG_ALT[lang])}" />
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:title" content="${esc(content.ogTitle || content.title)}" />
    <meta name="twitter:description" content="${esc(content.description)}" />
    <meta name="twitter:image" content="${ogImage}" />
    <meta name="twitter:image:alt" content="${esc(OG_ALT[lang])}" />

    <link rel="icon" href="${root}favicon.svg" type="image/svg+xml" />
    <link rel="apple-touch-icon" href="${root}apple-touch-icon.png" />
    <link rel="manifest" href="${root}${manifest}" />

    ${structuredData(ctx, content)}

    <link rel="stylesheet" href="${root}styles.css${v}" />
    <script>${THEME_SCRIPT}</script>
  </head>`;
}

const SECTIONS = [
  ["generator", "home", "i-key"],
  ["checker", "checker", "i-search"],
  ["wifi", "wifi", "i-wifi"],
];

function brand(ctx, extraClass) {
  const home = ctx.pages.find((target) => target.id === "home");
  return `<a class="brand${extraClass ? " " + extraClass : ""}" href="${ctx.href(home)}" aria-label="${esc(ctx.t.home)}">
          <span class="brand-mark">${icon("i-shield")}</span>
          <span class="brand-text">Forti<span class="brand-accent">Pass</span></span>
        </a>`;
}

function topbar(ctx) {
  const { t, page, lang } = ctx;
  const other = site.LANGUAGES.find((code) => code !== lang);
  const nav = SECTIONS.map(([section, id, iconId]) => {
    const target = ctx.pages.find((p) => p.id === id);
    // The passphrase and PIN pages belong to the Generator section without
    // being the page that link opens.
    const current = page.section === section ? (page.id === id ? ' aria-current="page"' : ' aria-current="true"') : "";
    return `<a href="${ctx.href(target)}"${current}>${icon(iconId)}<span>${t.sections[section]}</span></a>`;
  }).join("\n            ");
  return `<header class="topbar">
      <div class="container topbar-inner">
        ${brand(ctx)}

        <nav class="app-nav" aria-label="${esc(t.toolsNav)}">
          <div class="app-nav-inner">
            ${nav}
          </div>
        </nav>

        <div class="topbar-actions">
          <a class="lang-switch" href="${ctx.href(page, other)}" hreflang="${other}" lang="${other}" title="${esc(t.otherLanguageTitle)}">
            ${icon("i-globe", "icon-sm")}
            <span>${t.otherLanguage}</span>
          </a>
          <button type="button" class="icon-btn" id="themeBtn" aria-label="${esc(t.theme)}" title="${esc(t.themeTitle)}">
            ${icon("i-sun", "icon-sun")}
            ${icon("i-moon", "icon-moon")}
          </button>
        </div>
      </div>
    </header>`;
}

/** Link text keeps "Wi-Fi" on one line, as the build does for prose. */
const nowrapWifi = (label) => label.replace(/Wi-Fi/g, '<span class="nowrap">Wi-Fi</span>');

function footer(ctx) {
  const { t } = ctx;
  const year = site.UPDATED.slice(0, 4);
  const links = ctx.pages
    .map((target) => `<li><a href="${ctx.href(target)}"${target.id === ctx.page.id ? ' aria-current="page"' : ""}>${nowrapWifi(t.toolNames[target.id])}</a></li>`)
    .join("\n            ");
  return `<footer class="site-footer">
      <div class="container footer-grid">
        <div class="footer-about">
          ${brand(ctx, "brand-sm")}
          <p>${t.footerTagline}</p>
        </div>
        <ul class="footer-links">
            ${links}
        </ul>
        <div class="footer-bottom">
          <p>
            &copy; 2025–${year} ${site.AUTHOR} · ${t.footerFree} ·
            <a href="${site.REPO_URL}" rel="noopener">${t.footerSource}</a> ·
            <button type="button" class="link-btn" id="shortcutsBtn">${t.shortcutsLink}</button>
          </p>
          <p class="footer-note">${t.footerNote} ${t.footerCredit}</p>
        </div>
      </div>
    </footer>`;
}

function dialogs(ctx) {
  const { t, page } = ctx;
  const s = t.shortcutList;
  const rows = [];
  if (page.type === "generator") {
    rows.push(["<kbd>G</kbd>", s.g], ["<kbd>C</kbd>", s.c], ["<kbd>H</kbd>", s.h]);
    rows.push(["<kbd>1</kbd><kbd>2</kbd><kbd>3</kbd>", s.modes]);
  } else if (page.type === "wifi") {
    rows.push(["<kbd>G</kbd>", s.g], ["<kbd>C</kbd>", s.c]);
  }
  rows.push(["<kbd>T</kbd>", s.t], ["<kbd>?</kbd>", s.help], ["<kbd>Esc</kbd>", s.esc]);

  return `<div class="toast-stack" id="toasts" role="status" aria-live="polite"></div>

    <dialog class="dialog" id="shortcutsDialog" aria-labelledby="shortcutsTitle">
      <div class="dialog-head">
        <h2 id="shortcutsTitle">${t.shortcutsDialog}</h2>
        <button type="button" class="icon-btn" id="closeDialogBtn" aria-label="${esc(t.close)}">
          ${icon("i-close")}
        </button>
      </div>
      <dl class="shortcuts">
        ${rows.map(([keys, label]) => `<div><dt>${keys}</dt><dd>${label}</dd></div>`).join("\n        ")}
      </dl>
      <p class="dialog-note">${t.shortcutsNote}</p>
    </dialog>

    <dialog class="dialog" id="copyDialog" aria-labelledby="copyDialogTitle">
      <div class="dialog-head">
        <h2 id="copyDialogTitle">${t.copyDialogTitle}</h2>
        <button type="button" class="icon-btn" id="closeCopyDialogBtn" aria-label="${esc(t.close)}">
          ${icon("i-close")}
        </button>
      </div>
      <p class="dialog-note dialog-note-top">${t.copyDialogNote}</p>
      <textarea id="copyDialogText" class="text-input copy-text" rows="1" readonly spellcheck="false" aria-label="${esc(t.copyValue)}"></textarea>
    </dialog>

    <noscript>
      <div class="noscript">${t.noscript}</div>
    </noscript>`;
}

/** Scripts in load order: data and strings first, then core, then the UI. */
function scripts(ctx) {
  const { page, lang, root, assetVersion } = ctx;
  const files = [];
  // Word lists only where words are used: the checker knows English and
  // Czech words in either language, the passphrase page offers its own
  // language's list (and English), the Wi-Fi page makes words in its own.
  if (page.type === "checker") files.push("wordlist-en.js", "wordlist-cs.js");
  else if (page.mode === "passphrase") {
    files.push("wordlist-en.js");
    if (lang === "cs") files.push("wordlist-cs.js");
  } else if (page.type === "wifi") files.push(`wordlist-${lang}.js`);
  if (lang === "cs") files.push("locale-cs.js");
  if (page.type !== "article") files.push("core.js");
  if (page.type === "wifi") files.push("qr.js");
  files.push("script.js");
  return files
    .map((file) => `<script src="${root}${file}?v=${assetVersion}"></script>`)
    .join("\n    ");
}

function render(ctx, content, main) {
  const skipTarget = { generator: "generator", checker: "checker", wifi: "wifi", article: "main" }[
    ctx.page.type
  ];
  return `<!DOCTYPE html>
<html lang="${ctx.lang}" data-root="${ctx.root || "./"}" data-page="${ctx.page.type}">
  ${head(ctx, content)}
  <body>
    <a class="skip-link" href="#${skipTarget}">${ctx.t.skip}</a>

    <svg class="sprite" aria-hidden="true" focusable="false">
      <defs>${SPRITE_SYMBOLS}
      </defs>
    </svg>

    ${topbar(ctx)}

    <main id="main" class="container">
      ${main}
    </main>

    ${footer(ctx)}

    ${dialogs(ctx)}

    ${scripts(ctx)}
  </body>
</html>
`;
}

module.exports = { render, THEME_SCRIPT, THEME_COLORS, CSP, OG_IMAGE };
