function manifest(lang) {
  const m = MANIFESTS[lang];
  const base = lang === "en" ? "" : lang + "/";
  const up = "../".repeat(depthOf(base));
  const local = (page) => "./" + page.paths[lang].slice(base.length);
  return (
    JSON.stringify(
      {
        id: m.id,
        name: m.name,
        short_name: m.short_name,
        description: m.description,
        start_url: "./",
        scope: "./",
        display: "standalone",
        background_color: layout.THEME_COLORS.dark,
        theme_color: layout.THEME_COLORS.dark,
        categories: ["utilities", "security", "productivity"],
        lang: lang,
        dir: "ltr",
        icons: ICONS.map((icon) => Object.assign({}, icon, { src: up + icon.src })),
        shortcuts: m.shortcuts.map(([name, short, id]) => ({
          name: name,
          short_name: short,
          url: local(pageById(id)),
        })),
      },
      null,
      2
    ) + "\n"
  );
}

function sitemap() {
  const urls = [];
  site.PAGES.forEach((page) => {
    site.LANGUAGES.forEach((lang) => {
      const alternates = site.LANGUAGES.map(
        (code) =>
          `    <xhtml:link rel="alternate" hreflang="${code}" href="${site.SITE_URL}${page.paths[code]}" />`
      ).concat(
        `    <xhtml:link rel="alternate" hreflang="x-default" href="${site.SITE_URL}${page.paths.en}" />`
      );
      urls.push(`  <url>
    <loc>${site.SITE_URL}${page.paths[lang]}</loc>
    <lastmod>${site.UPDATED}</lastmod>
${alternates.join("\n")}
  </url>`);
    });
  });
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by build/build.js. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls.join("\n")}
</urlset>
`;
}

function robots() {
  return `User-agent: *
Allow: /

Sitemap: ${site.SITE_URL}sitemap.xml
`;
}

/* -------------------------------------------------------- service worker */

const VERSIONED_ASSETS = [
  "styles.css",
  "wordlist-en.js",
  "wordlist-cs.js",
  "locale-cs.js",
  "core.js",
  "qr.js",
  "script.js",
];

const STATIC_ASSETS = [
  "manifest.json",
  "cs/manifest.json",
  "favicon.svg",
  "icon.svg",
  "icon-192.png",
  "icon-512.png",
  "icon-maskable-512.png",
  "apple-touch-icon.png",
];

function serviceWorker() {
  const template = fs.readFileSync(path.join(__dirname, "sw.template.js"), "utf8");
  const pages = [];
  site.PAGES.forEach((page) => site.LANGUAGES.forEach((lang) => pages.push(page.paths[lang])));
  const list = (items) => "[\n" + items.map((item) => `  "${item}",`).join("\n") + "\n]";
  return template
    .replace("__ASSET_VERSION__", site.ASSET_VERSION)
    .replace("__PAGES__", list(pages))
    .replace("__VERSIONED__", list(VERSIONED_ASSETS))
    .replace("__STATIC__", list(STATIC_ASSETS));
}

/* ------------------------------------------------------------------ main */

/** Every generated file: relative path → contents. */
function renderSite() {
  const files = new Map();
  site.LANGUAGES.forEach((lang) => {
    const facts = makeFacts(lang);
    site.PAGES.forEach((page) => {
      files.set(page.paths[lang] + "index.html", renderPage(page, lang, facts));
    });
  });
  files.set("404.html", render404());
  files.set("wordlist-en.js", wordlistScript("en"));
  files.set("wordlist-cs.js", wordlistScript("cs"));
  files.set("manifest.json", manifest("en"));
  files.set("cs/manifest.json", manifest("cs"));
  files.set("sitemap.xml", sitemap());
  files.set("robots.txt", robots());
  files.set("sw.js", serviceWorker());
  return files;
}

function main() {
  const check = process.argv.includes("--check");
  const files = renderSite();
  const stale = [];
  files.forEach((contents, file) => {
    const target = path.join(ROOT, file);
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : null;
    if (current === contents) return;
    stale.push(file);
    if (!check) {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, contents);
    }
  });
  if (check) {
    if (stale.length) {
      console.error("Out of date — run `npm run build`:\n  " + stale.join("\n  "));
      process.exit(1);
    }
    console.log(`All ${files.size} generated files are up to date.`);
  } else {
    console.log(stale.length ? "Wrote:\n  " + stale.join("\n  ") : "Nothing to do.");
  }
}

if (require.main === module) main();

