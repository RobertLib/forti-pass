/* Static-site build. Renders every page in every language, the word-list
   scripts, the manifests, the sitemap and the service worker from the
   sources in build/ and wordlists/.

     npm run build          write the files
     node build/build.js --check
                            exit 1 if any generated file is out of date
                            (the test suite runs this check too)

   Generated files are committed, so GitHub Pages can serve the repository
   as it is — no CI step needed. */

