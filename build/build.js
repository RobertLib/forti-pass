/* ----------------------------------------------------------------- pages */

const pageById = (id) => site.PAGES.find((page) => page.id === id);
const depthOf = (p) => p.split("/").filter(Boolean).length;

function makeContext(page, lang, facts) {
  const root = "../".repeat(depthOf(page.paths[lang]));
  const ctx = {
    page,
    lang,
    t: strings[lang],
    pages: site.PAGES,
    root,
    url: site.SITE_URL + page.paths[lang],
    facts,
    // The generator offers the page's own language first.
    languages: lang === "cs" ? ["cs", "en"] : ["en"],
  };
  ctx.href = (target, targetLang) => root + target.paths[targetLang || lang] || "./";
  return ctx;
}

/** Title, one-line introduction and, on tool pages, the privacy promises. */
function pageHead(t, page, content) {
  const trust =
    page.type === "article"
      ? ""
      : `
          <ul class="trust">
            ${t.trust.map(([iconId, label]) => `<li>${icon(iconId, "icon-sm")}${label}</li>`).join("\n            ")}
          </ul>`;
  return `<header class="page-head">
          <h1>${content.h1}</h1>
          <p class="lede">${content.lede}</p>${trust}
        </header>`;
}

function faq(t, items) {
  if (!items || !items.length) return "";
  return `<section class="content faq-section" aria-labelledby="faqHeading">
          <h2 id="faqHeading">${t.faqHeading}</h2>
          <div class="faq">
            ${items
              .map(
                ([question, answer]) => `<details>
              <summary>${question}</summary>
              <p>${answer}</p>
            </details>`
              )
              .join("\n            ")}
          </div>
        </section>`;
}

function renderPage(page, lang, facts) {
  const ctx = makeContext(page, lang, facts);
  const t = ctx.t;
  const labels = TABLE_LABELS[lang];
  const helpers = {
    crackTable: (tableLabels) => components.crackTable(ctx, tableLabels),
    passphraseTable: (list, from, to) =>
      components.passphraseTable(
        ctx,
        list === "cs" ? labels.passphraseCs : labels.passphrase,
        list,
        from,
        to
      ),
    pinTable: (lengths) => components.pinTable(ctx, labels.pin, lengths),
  };
  const href = (id, targetLang) => ctx.href(pageById(id), targetLang);
  const content = CONTENT[lang](facts, href, helpers)[page.id];

  const tool = {
    generator: () => components.generator(t, ctx),
    checker: () => components.checker(t, ctx),
    wifi: () => components.wifi(t),
    article: () => "",
  }[page.type]();

  const reading = [content.body, faq(t, content.faq)].filter(Boolean).join("\n\n        ");
  const main = [
    pageHead(t, page, content),
    tool,
    `<div class="reading${tool ? "" : " reading-article"}">
        ${reading}
        </div>`,
  ]
    .filter(Boolean)
    .join("\n\n        ");

  return layout.render(ctx, content, main);
}

/** GitHub Pages serves 404.html at whatever URL was missed, so it uses
    absolute paths and no service worker. */
function render404() {
  const base = new URL(site.SITE_URL).pathname;
  const links = (lang) =>
    site.PAGES.map(
      (page) => `<li><a href="${base}${page.paths[lang]}">${strings[lang].toolNames[page.id]}</a></li>`
    ).join("\n          ");
  return `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <!-- Generated by build/build.js. -->
    <meta http-equiv="Content-Security-Policy" content="default-src 'self'; script-src 'none'; style-src 'self'; img-src 'self'; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="robots" content="noindex" />
    <title>Page not found · Stránka nenalezena | FortiPass</title>
    <link rel="icon" href="${base}favicon.svg" type="image/svg+xml" />
    <link rel="stylesheet" href="${base}styles.css?v=${site.ASSET_VERSION}" />
  </head>
  <body>
    <main class="container not-found">
      <section class="page-head">
        <h1>Page not found</h1>
        <p class="lede">The page you asked for does not exist. Pick a tool instead:</p>
        <ul class="not-found-links">
          ${links("en")}
        </ul>
      </section>
      <section class="page-head" lang="cs">
        <h2>Stránka nenalezena</h2>
        <p class="lede">Tahle stránka neexistuje. Vyberte si nástroj:</p>
        <ul class="not-found-links">
          ${links("cs")}
        </ul>
      </section>
    </main>
  </body>
</html>
`;
}

